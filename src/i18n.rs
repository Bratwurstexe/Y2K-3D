//! German / English texts. The program is written with German texts; in English mode each one
//! is looked up here.

use std::collections::HashMap;
use std::fmt::Display;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static ENGLISH: AtomicBool = AtomicBool::new(false);

pub fn set_english(on: bool) {
    ENGLISH.store(on, Ordering::Relaxed);
}

pub fn is_english() -> bool {
    ENGLISH.load(Ordering::Relaxed)
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| PAIRS.iter().copied().collect())
}

/// The text in the chosen language.
pub fn tr(de: &'static str) -> &'static str {
    if !is_english() {
        return de;
    }
    table().get(de).copied().unwrap_or(de)
}

/// For names that live in the data (material and sky presets): translated when known.
pub fn tr_name(de: &str) -> String {
    if !is_english() {
        return de.to_string();
    }
    let (base, star) = match de.strip_suffix('*') {
        Some(b) => (b, "*"),
        None => (de, ""),
    };
    match table().get(base) {
        Some(en) => format!("{en}{star}"),
        None => de.to_string(),
    }
}

/// Fills `{}` and `{:.N}` placeholders in order.
pub fn fill(template: &str, args: &[&dyn Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut it = args.iter();
    let mut chars = template.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '{' {
            if chars.peek() == Some(&'{') {
                chars.next();
                out.push('{');
                continue;
            }
            let mut spec = String::new();
            for d in chars.by_ref() {
                if d == '}' {
                    break;
                }
                spec.push(d);
            }
            let Some(a) = it.next() else { continue };
            match spec
                .strip_prefix(":.")
                .and_then(|p| p.parse::<usize>().ok())
            {
                Some(p) => out.push_str(&format!("{:.*}", p, a)),
                None => out.push_str(&a.to_string()),
            }
        } else if c == '}' && chars.peek() == Some(&'}') {
            chars.next();
            out.push('}');
        } else {
            out.push(c);
        }
    }
    out
}

/// Like `format!`, but the template is translated first.
#[macro_export]
macro_rules! trf {
    ($fmt:literal $(, $a:expr)* $(,)?) => {
        $crate::i18n::fill($crate::i18n::tr($fmt), &[$(&$a as &dyn std::fmt::Display),*])
    };
}

